package backend.realtime;

/**
 * The Enum OccupancyLevel -> an enum class which contains the rating adjectives of the occupancy level of a vehicle.
 */
public enum OccupancyLevel {
	
	/** The empty. */
	EMPTY,
	
	/** The low. */
	LOW,
	
	/** The medium. */
	MEDIUM,
	
	/** The high. */
	HIGH,
	
	/** The full. */
	FULL,
	
	/** The unknown. */
	UNKNOWN

}
